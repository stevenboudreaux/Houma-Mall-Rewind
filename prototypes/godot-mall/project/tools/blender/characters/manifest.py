"""models/characters/characters.json: everything the body editor (B2) needs, data-driven.
Collects .scratch/chars/body_*.json (body.py), pieces_*.json (hair / outfits) and keys.json,
presets.json. Run after building: python3 manifest.py"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sliders
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SC = os.path.join(PROJ, ".scratch", "chars")

def main():
    K = sliders.KEYS
    m = {"_": "B1 character bodies, hair and outfit pieces (design/godot-characters.md). Generated by tools/blender/characters/manifest.py; do not edit by hand.",
         "version": 1, "skeleton": "mixamorig_* (65 bones), rest = Ch01 T-pose rotations (npc/anims.json rest)",
         "bodies": {}, "sliders": [], "correctives": [], "presets": {}, "skin_tones": SKIN_TONES, "iris_colors": IRIS,
         "hair_colors": HAIR_COLORS, "layers": LAYERS, "regions": None, "pieces": []}
    for sex in ("female", "male"):
        p = os.path.join(SC, "body_%s.json" % sex)
        if not os.path.exists(p):
            continue
        i = json.load(open(p))
        lo, hi = i["lo"], i["hi"]
        m["regions"] = lo["regions"]
        m["bodies"][sex] = {"glb": "res://models/characters/" + lo["file"], "glb_hi": "res://models/characters/" + hi["file"],
                            "tris": sum(lo["tris"].values()), "tris_hi": sum(hi["tris"].values()), "tris_by_mesh": lo["tris"],
                            "height_m": round(i["height_m"], 3), "hips_height": round(i["hips_height"], 4),
                            "shapes": lo["shapes"], "bones": i["bones"], "joints": i["joints"],
                            "materials": {"skin_body": "skin", "skin_face": "face (swap for a face pass)", "eye_iris": "iris tint", "lashes": "hair tint"}}
    for s in K["sliders"]:
        d = {"name": s["name"], "group": s["group"], "range": s["range"]}
        for k in ("sex", "note", "years"):
            if k in s: d[k] = s[k]
        if "bones" in s:
            d["bones"] = s["bones"]; d["kind"] = "skeleton"
        else:
            d["kind"] = "shape"; d["shapes"] = [s["name"] + g for g in ("+", "-") if g in s]
        m["sliders"].append(d)
    m["correctives"] = [{"shape": "c_" + "_".join(c), "product_of": c} for c in K["correct"]]
    m["presets"] = {k: v for k, v in sliders.PRESETS.items() if not k.startswith("_")}
    for p in sorted(glob.glob(os.path.join(SC, "piece_*.json"))):
        e = json.load(open(p))
        if str(e.get("slot", "")).startswith("base_"):
            continue      # B-FIX: no base-layer pieces in the live game (a stale scratch file is skipped)
        m["pieces"].append(e)
    out = os.path.join(PROJ, "models", "characters", "characters.json")
    json.dump(m, open(out, "w"), indent=1)
    print("MANIFEST", out, len(m["pieces"]), "pieces")

# sRGB tones, very light -> very dark (the skin tint multiplies skin_albedo.png)
SKIN_TONES = [["porcelain", "#f6e1d3"], ["fair", "#eccbb4"], ["light", "#e0b393"], ["light medium", "#cf9a76"],
              ["medium", "#b98460"], ["tan", "#a06c48"], ["brown", "#83553a"], ["dark brown", "#66402b"],
              ["deep", "#4b2e20"], ["very deep", "#362016"]]
IRIS = [["brown", "#5a3a22"], ["dark brown", "#3a2414"], ["hazel", "#7d6a3c"], ["green", "#5b7448"], ["blue", "#5e7fa6"], ["grey", "#7f8a92"]]
HAIR_COLORS = [["black", "#1b1714"], ["dark brown", "#3b2a1f"], ["brown", "#5e4330"], ["light brown", "#8a6a4c"], ["auburn", "#7a3a22"],
               ["red", "#a04a28"], ["dark blonde", "#a88a5e"], ["blonde", "#d2b27c"], ["platinum", "#e6dcc8"], ["grey", "#9a9690"], ["white", "#e8e6e2"]]
LAYERS = {"0": "unused (no base layer: the body carries a painted one; B-FIX)", "1": "underlayer (tee under a flannel, undershirt)", "2": "top / bottom", "3": "outerwear", "4": "shoes", "5": "extras (cap, glasses, watch)"}

if __name__ == "__main__":
    main()
